CREATE TABLE categoria (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(100 CHAR) NOT NULL UNIQUE,
  descripcion VARCHAR2(500 CHAR),
  activa NUMBER(1) DEFAULT 1 NOT NULL,
  version NUMBER DEFAULT 1 NOT NULL,
  autor_sub VARCHAR2(255 CHAR) NOT NULL,
  actualizada_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (activa IN (0,1)),
  CHECK (version >= 1)
);

CREATE TABLE politica_plazo (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prioridad VARCHAR2(10 CHAR) NOT NULL,
  version NUMBER NOT NULL,
  horas NUMBER(8,2) NOT NULL,
  creada_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  autor_sub VARCHAR2(255 CHAR) NOT NULL,
  CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
  CHECK (horas > 0),
  CHECK (version >= 1),
  UNIQUE (prioridad,version)
);

